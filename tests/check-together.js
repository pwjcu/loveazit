const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const context=vm.createContext({Intl,Date,Object,Number,String,Math});
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname,'../assets/together.js'),'utf8'),context);
const edit=(state,day,slot,kind,value)=>context.togetherEdit(state,day,slot,kind,value);
const s={hearts:8};const day='2026-09-12';
assert.equal(edit(s,day,1,'mood','sun').ok,true);
assert.equal(edit(s,day,2,'mood','hug').ok,true);
assert.equal(edit(s,day,1,'answer','고마워').ok,true);
assert.equal(s.together.total,0,'Both people must leave an actual answer');
edit(s,day,2,'answer','나도 고마워');
assert.equal(s.together.total,1);
assert.equal(s.together.days[day].completed,true);
assert.equal(edit(s,day,2,'answer','나도 고마워').ok,false,'Idempotent retries');
edit(s,day,1,'mood','cloud');edit(s,day,2,'answer','수정한 답변');
assert.equal(s.together.total,1,'Editing cannot farm stamps');
assert.equal(s.hearts,8,'No currency reward outside the daily cap');
assert.equal(edit(s,day,1,'answer','   ').ok,false);
assert.equal(edit(s,day,3,'mood','sun').ok,false);
assert.equal(edit(s,day,1,'mood','unknown').ok,false);
assert.equal(edit(s,day,1,'mood','toString').ok,false);
edit(s,day,1,'answer','가'.repeat(200));
assert.equal(s.together.days[day][1].answer.length,140);
for(let i=0;i<90;i++)edit(s,new Date(Date.UTC(2027,0,1+i)).toISOString().slice(0,10),1,'mood','sun');
assert.equal(Object.keys(s.together.days).length,91,'Daily questions and answers are never pruned');
assert.equal(s.together.total,1,'All-time stamps survive growing history');
assert.equal(context.togetherDay(new Date('2026-09-12T15:00:00Z')),'2026-09-13','Both clients use Korean midnight');
context.togetherReserve(s,'2026-09-13');
assert.equal(context.togetherPrompt('2026-09-12',s),s.together.days['2026-09-12'].question);
assert.notEqual(context.togetherPrompt('2026-09-12',s),context.togetherPrompt('2026-09-13',s));
console.log('Together: 18 checks passed (completion, retry, permanent history, timezone, currency isolation).');
